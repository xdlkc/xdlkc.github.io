  function buildTocIntoContainer(toc, headingElements) {
    if (!toc || !toc.querySelector) return;
    // doc is already closure-scoped, no need for ownerDocument or globalThis.document
    if (!doc?.createElement) return;

    // If TOC already has anchors, respect existing markup (likely generated by Hexo helper).
    const existingLinks = toc.querySelectorAll('a[href^="#"]');
    if (existingLinks && existingLinks.length > 0) return;

    const headings = Array.isArray(headingElements) ? headingElements : [];
    if (headings.length === 0) return;

    // Clear any placeholder content.
    try {
      toc.innerHTML = '';
    } catch {
      // ignore
    }

    // Build a nested <ol> structure based on heading levels.
    // H3 nests under the nearest H2, H4 nests under the nearest H3 (or H2 if no H3).
    const topOl = doc.createElement('ol');

    const toSafeLevel = (heading) => {
      const tag = String(heading?.tagName || '').toUpperCase();
      const level = tag.startsWith('H') ? Number(tag.slice(1)) : 2;
      if (level === 2 || level === 3 || level === 4) return level;
      return 2;
    };

    // Stack entries: { level, li, ol }
    // `ol` is the list to append children into (created lazily on the li).
    const stack = [{ level: 1, li: null, ol: topOl }];

    const ensureChildOl = (li) => {
      if (!li) return null;
      const existing = li.querySelector?.(':scope > ol');
      if (existing) return existing;
      const ol = doc.createElement('ol');
      li.appendChild(ol);
      return ol;
    };

    headings.forEach((heading) => {
      const id = heading.getAttribute('id');
      if (!id) return;

      // Clone the heading to extract text without the anchor link.
      const clonedHeading = heading.cloneNode(true);
      const anchor = clonedHeading.querySelector(':scope > .heading-anchor');
      if (anchor) {
        anchor.remove();
      }
      const text = String(clonedHeading.textContent || '').trim(); // Get text from clone
      if (!text) return;

      // Normalize unexpected levels into a safe range.
      const safeLevel = toSafeLevel(heading);

      // If the document starts with h3/h4 (or has jumps), still produce a usable TOC.
      // Pop until we find a parent level smaller than the current level.
      while (stack.length > 1 && stack[stack.length - 1].level >= safeLevel) {
        stack.pop();
      }

      const parent = stack[stack.length - 1];
      let parentOl = parent.ol;

      // If parent is a real heading item, we may need to append into its child <ol>.
      if (parent.li && parent.level >= 2) {
        parentOl = ensureChildOl(parent.li);
      }

      // Safety fallback.
      if (!parentOl) parentOl = topOl;

      const li = doc.createElement('li');
      li.className = `toc-nav-level-${safeLevel}`;

      const a = doc.createElement('a');
      a.className = 'toc-nav-link';
      a.setAttribute('href', `#${id}`);
      a.textContent = text;
      a.setAttribute('title', text);

      li.appendChild(a);
      parentOl.appendChild(li);

      // Push current item to stack so deeper headings can nest under it.
      stack.push({ level: safeLevel, li, ol: null });
    });

    toc.appendChild(topOl);
  }

  function enhanceCollapsibleToc(toc, {
    storage = win.localStorage, // Use win.localStorage
    storageKey = 'xdlkc:toc:collapsed'
  } = {}) {
    if (!toc || !toc.querySelectorAll || !doc?.createElement) return;

    const safeKey = String(storageKey || 'xdlkc:toc:collapsed');

    const readCollapsedSet = () => {
      try {
        const raw = storage?.getItem?.(safeKey);
        if (!raw) return new Set();
        const parsed = JSON.parse(raw);
        if (!Array.isArray(parsed)) return new Set();
        return new Set(parsed.map((x) => String(x)).filter(Boolean));
      } catch {
        return new Set();
      }
    };

    const writeCollapsedSet = (set) => {
      try {
        if (!storage?.setItem) return;
        storage.setItem(safeKey, JSON.stringify(Array.from(set)));
      } catch {
        // ignore
      }
    };

    const collapsedSet = readCollapsedSet();

    const items = Array.from(toc.querySelectorAll('li'));

    items.forEach((li, idx) => {
      // Only items with nested list should have a collapse button.
      const childList = li.querySelector(':scope > ol, :scope > ul');
      if (!childList) return;

      const firstLink = li.querySelector(':scope > a');
      const href = String(firstLink?.getAttribute?.('href') || '').trim();
      const id = href.startsWith('#') ? href : `idx:${idx}`;

      // Idempotent: avoid inserting twice.
      const existingBtn = li.querySelector(':scope > .toc-collapse-btn');

      const applyCollapsed = (collapsed, btn) => {
        if (collapsed) li.classList.add('is-collapsed');
        else li.classList.remove('is-collapsed');
        btn?.setAttribute?.('aria-expanded', collapsed ? 'false' : 'true');
      };

      // Restore persisted state (even if button already exists).
      const shouldCollapse = collapsedSet.has(id);

      if (existingBtn) {
        applyCollapsed(shouldCollapse, existingBtn);
        return;
      }

      const btn = doc.createElement('button');
      btn.type = 'button';
      btn.className = 'toc-collapse-btn';
      btn.setAttribute('aria-label', '折叠/展开子标题');

      applyCollapsed(shouldCollapse, btn);

      btn.addEventListener('click', (event) => {
        event.preventDefault();
        event.stopPropagation();

        const collapsed = li.classList.toggle('is-collapsed');
        btn.setAttribute('aria-expanded', collapsed ? 'false' : 'true');

        if (collapsed) collapsedSet.add(id);
        else collapsedSet.delete(id);

        writeCollapsedSet(collapsedSet);
      });

      // Insert before the first link so the button is the first focusable in the item.
      if (firstLink?.parentNode) {
        li.insertBefore(btn, firstLink);
      } else {
        li.insertBefore(btn, li.firstChild);
      }
    });
  }

