  // If the TOC already exists (generated by Hexo), its anchor ids may not match
  // our client-side slugify logic. In that case, prefer the TOC's href ids and
  // sync them onto the corresponding headings (best-effort by link order + text).
  // Also dedupe duplicate ids by rewriting later TOC hrefs to `id-2`, `id-3`, ...
  function syncHeadingIdsWithToc(toc, headingElements) {
    if (!toc?.querySelectorAll) return;

    const links = Array.from(toc.querySelectorAll('a[href^="#"]'));
    if (links.length === 0) return;

    const headings = Array.isArray(headingElements) ? headingElements : [];
    if (headings.length === 0) return;

    const normalizedHeadingText = (el) => String(el?.textContent || '').trim();

    // Build candidates grouped by visible text, preserving order.
    const byText = new Map();
    headings.forEach((h) => {
      const t = normalizedHeadingText(h);
      if (!t) return;
      const arr = byText.get(t) || [];
      arr.push(h);
      byText.set(t, arr);
    });

    const usedIds = new Set();

    const makeUnique = (base) => {
      const safeBase = String(base || '').trim() || 'section';
      if (!usedIds.has(safeBase)) return safeBase;
      let i = 2;
      while (usedIds.has(`${safeBase}-${i}`)) i++;
      return `${safeBase}-${i}`;
    };

    links.forEach((link) => {
      const href = String(link.getAttribute('href') || '');
      const rawId = href.startsWith('#') ? href.slice(1) : '';
      if (!rawId) return;

      const text = String(link.textContent || '').trim();
      if (!text) return;

      const candidates = byText.get(text) || [];
      const heading = candidates.shift();
      if (!heading) return;

      // Persist the shifted queue.
      byText.set(text, candidates);

      const uniqueId = makeUnique(rawId);
      usedIds.add(uniqueId);

      try {
        heading.setAttribute('id', uniqueId);
      } catch {
        // ignore
      }

      // If dedup changed the id, also rewrite the TOC href so it stays correct.
      if (uniqueId !== rawId) {
        try {
          link.setAttribute('href', `#${uniqueId}`);
        } catch {
          // ignore
        }
      }
    });
  }

