(function(root, factory) {
  if (typeof module === 'object' && module.exports) {
    module.exports = factory();
  } else {
    root.TocScrollSpy = factory();
  }
})(typeof self !== 'undefined' ? self : this, function() {
  function slugifyHeading(text) {
    return String(text || '')
      .trim()
      .toLowerCase()
      // Replace common separators with spaces so they collapse into one dash.
      .replace(/[\\/|_]+/g, ' ')
      // Drop punctuation but keep CJK, letters, digits, spaces and hyphens.
      .replace(/[^\p{L}\p{N}\p{Script=Han}\s-]+/gu, '')
      .trim()
      .replace(/\s+/g, '-')
      .replace(/-+/g, '-');
  }

  /**
   * Decide which heading should be considered active given scrollY.
   * headings: [{id, top}] where top is the document Y offset for the heading.
   */
  function pickActiveHeadingId({ scrollY, headings, offset = 0 } = {}) {
    if (!Array.isArray(headings) || headings.length === 0) return null;

    const y = (Number.isFinite(scrollY) ? scrollY : 0) + offset;

    // If before the first heading, keep first active.
    if (y < headings[0].top) return headings[0].id;

    // Find the last heading whose top <= y.
    for (let i = headings.length - 1; i >= 0; i--) {
      if (y >= headings[i].top) return headings[i].id;
    }

    return headings[0].id;
  }

  function getHeadingTopInDocument(element) {
    const rect = element.getBoundingClientRect();
    const scrollY = window.scrollY || window.pageYOffset || 0;
    return rect.top + scrollY;
  }

  function toNumber(value, fallback = 0) {
    const n = Number(value);
    return Number.isFinite(n) ? n : fallback;
  }

  function computeScrollTop({ targetTop, headerHeight, margin = 12 } = {}) {
    const top = toNumber(targetTop, 0);
    const header = toNumber(headerHeight, 0);
    const m = toNumber(margin, 12);
    return Math.max(0, Math.round(top - header - m));
  }

  // Compute next scrollTop for a scrollable TOC container so that the active link is visible.
  // All coordinates are relative to the container's scroll content (not the page).
  function computeTocScrollTopToReveal({
    containerScrollTop = 0,
    containerHeight = 0,
    linkTop = 0,
    linkHeight = 0
  } = {}) {
    const scrollTop = toNumber(containerScrollTop, 0);
    const height = Math.max(0, toNumber(containerHeight, 0));
    const top = Math.max(0, toNumber(linkTop, 0));
    const h = Math.max(0, toNumber(linkHeight, 0));

    if (height <= 0) return scrollTop;

    const viewTop = scrollTop;
    const viewBottom = scrollTop + height;
    const linkBottom = top + h;

    // Above the visible window: align link top to view top.
    if (top < viewTop) return top;

    // Below the visible window: align link bottom to view bottom.
    if (linkBottom > viewBottom) return Math.max(0, linkBottom - height);

    return scrollTop;
  }

  function ensureHeadingIds(headings) {
    const used = new Set();

    headings.forEach((heading) => {
      const existing = heading.getAttribute('id');
      if (existing) {
        used.add(existing);
        return;
      }

      const base = slugifyHeading(heading.textContent || '') || 'section';
      let id = base;
      let i = 2;
      while (used.has(id)) {
        id = `${base}-${i++}`;
      }
      heading.setAttribute('id', id);
      used.add(id);
    });
  }

  function buildTocIntoContainer(toc, headingElements) {
    if (!toc || !toc.querySelector) return;

    // If TOC already has anchors, respect existing markup (likely generated by Hexo helper).
    const existingLinks = toc.querySelectorAll('a[href^="#"]');
    if (existingLinks && existingLinks.length > 0) return;

    const headings = Array.isArray(headingElements) ? headingElements : [];
    if (headings.length === 0) return;

    // Clear any placeholder content.
    try {
      toc.innerHTML = '';
    } catch {
      // ignore
    }

    const list = document.createElement('ol');

    headings.forEach((heading) => {
      const id = heading.getAttribute('id');
      if (!id) return;

      const text = String(heading.textContent || '').trim();
      if (!text) return;

      const tag = String(heading.tagName || '').toUpperCase();
      const level = tag.startsWith('H') ? Number(tag.slice(1)) : 2;
      const safeLevel = level === 2 || level === 3 || level === 4 ? level : 2;

      const li = document.createElement('li');
      li.className = `toc-nav-level-${safeLevel}`;

      const a = document.createElement('a');
      a.className = 'toc-nav-link';
      a.setAttribute('href', `#${id}`);
      a.textContent = text;

      li.appendChild(a);
      list.appendChild(li);
    });

    toc.appendChild(list);
  }

  function enhanceCollapsibleToc(
    toc,
    {
      document: doc = document,
      storage = globalThis.localStorage,
      storageKey = 'xdlkc:toc:collapsed'
    } = {}
  ) {
    if (!toc || !toc.querySelectorAll || !doc?.createElement) return;

    const safeKey = String(storageKey || 'xdlkc:toc:collapsed');

    const readCollapsedSet = () => {
      try {
        const raw = storage?.getItem?.(safeKey);
        if (!raw) return new Set();
        const parsed = JSON.parse(raw);
        if (!Array.isArray(parsed)) return new Set();
        return new Set(parsed.map((x) => String(x)).filter(Boolean));
      } catch {
        return new Set();
      }
    };

    const writeCollapsedSet = (set) => {
      try {
        if (!storage?.setItem) return;
        storage.setItem(safeKey, JSON.stringify(Array.from(set)));
      } catch {
        // ignore
      }
    };

    const collapsedSet = readCollapsedSet();

    const items = Array.from(toc.querySelectorAll('li'));

    items.forEach((li, idx) => {
      // Only items with nested list should have a collapse button.
      const childList = li.querySelector(':scope > ol, :scope > ul');
      if (!childList) return;

      const firstLink = li.querySelector(':scope > a');
      const href = String(firstLink?.getAttribute?.('href') || '').trim();
      const id = href.startsWith('#') ? href : `idx:${idx}`;

      // Idempotent: avoid inserting twice.
      const existingBtn = li.querySelector(':scope > .toc-collapse-btn');

      const applyCollapsed = (collapsed, btn) => {
        if (collapsed) li.classList.add('is-collapsed');
        else li.classList.remove('is-collapsed');
        btn?.setAttribute?.('aria-expanded', collapsed ? 'false' : 'true');
      };

      // Restore persisted state (even if button already exists).
      const shouldCollapse = collapsedSet.has(id);

      if (existingBtn) {
        applyCollapsed(shouldCollapse, existingBtn);
        return;
      }

      const btn = doc.createElement('button');
      btn.type = 'button';
      btn.className = 'toc-collapse-btn';
      btn.setAttribute('aria-label', '折叠/展开子标题');

      applyCollapsed(shouldCollapse, btn);

      btn.addEventListener('click', (event) => {
        event.preventDefault();
        event.stopPropagation();

        const collapsed = li.classList.toggle('is-collapsed');
        btn.setAttribute('aria-expanded', collapsed ? 'false' : 'true');

        if (collapsed) collapsedSet.add(id);
        else collapsedSet.delete(id);

        writeCollapsedSet(collapsedSet);
      });

      // Insert before the first link so the button is the first focusable in the item.
      if (firstLink?.parentNode) {
        li.insertBefore(btn, firstLink);
      } else {
        li.insertBefore(btn, li.firstChild);
      }
    });
  }

  function initTocScrollSpy({
    tocSelector = '.toc-nav',
    contentSelector = '.article-content',
    headingSelector = 'h2, h3, h4'
  } = {}) {
    const toc = document.querySelector(tocSelector);
    if (!toc) return;

    const content = document.querySelector(contentSelector) || document;
    const headingElements = Array.from(content.querySelectorAll(headingSelector));
    if (headingElements.length === 0) return;

    // Ensure heading ids exist so TOC anchors have targets.
    ensureHeadingIds(headingElements);

    // Fallback: some pages may not have TOC markup generated by the template.
    // If `.toc-nav` exists but contains no anchors, auto-generate a minimal TOC.
    buildTocIntoContainer(toc, headingElements);

    // Enhance TOC UX: allow collapsing nested sections.
    enhanceCollapsibleToc(toc);

    let tocLinks = Array.from(toc.querySelectorAll('a[href^="#"]'));
    if (tocLinks.length === 0) return;

    const header = document.querySelector('.article-nav');

    // Smooth scroll on click with header offset (keep default anchor behavior as fallback).
    tocLinks.forEach((link) => {
      link.addEventListener('click', (event) => {
        const href = link.getAttribute('href') || '';
        const id = href.startsWith('#') ? href.slice(1) : '';
        if (!id) return;

        const target = document.getElementById(id);
        if (!target) return;

        event.preventDefault();

        // Mobile TOC is wrapped in <details class="toc-mobile">.
        // After choosing a section, auto-close it to avoid covering content.
        const mobileDetails = link.closest?.('details.toc-mobile');
        if (mobileDetails?.hasAttribute?.('open')) {
          mobileDetails.removeAttribute('open');
        }

        const headerHeight = header?.getBoundingClientRect
          ? header.getBoundingClientRect().height
          : 0;
        const targetTop = getHeadingTopInDocument(target);
        const scrollTop = computeScrollTop({ targetTop, headerHeight });

        try {
          window.scrollTo({ top: scrollTop, behavior: 'smooth' });
          history.pushState(null, '', `#${id}`);
        } catch (e) {
          // Unsupported: fall back to default jump.
          location.hash = `#${id}`;
        }
      });
    });

    const headingMeta = headingElements.map((el) => ({
      id: el.id,
      top: getHeadingTopInDocument(el)
    }));

    const linkById = new Map();
    tocLinks.forEach((link) => {
      const href = link.getAttribute('href') || '';
      const id = href.startsWith('#') ? href.slice(1) : null;
      if (!id) return;
      linkById.set(id, link);
    });

    let scheduled = false;
    let activeId = null;

    const clearActive = () => {
      tocLinks.forEach((link) => {
        link.classList.remove('is-active');
        link.removeAttribute('aria-current');
      });
    };

    const setActive = (id) => {
      if (!id || id === activeId) return;
      activeId = id;
      clearActive();
      const link = linkById.get(id);
      if (!link) return;
      link.classList.add('is-active');
      link.setAttribute('aria-current', 'true');

      // Keep the active TOC entry visible inside a long TOC container.
      try {
        const height = toc.clientHeight || 0;
        if (height > 0 && toc.scrollHeight > height) {
          const nextScrollTop = computeTocScrollTopToReveal({
            containerScrollTop: toc.scrollTop || 0,
            containerHeight: height,
            linkTop: link.offsetTop || 0,
            linkHeight: link.offsetHeight || 0
          });
          if (Number.isFinite(nextScrollTop) && Math.abs(nextScrollTop - (toc.scrollTop || 0)) > 1) {
            toc.scrollTop = nextScrollTop;
          }
        }
      } catch {
        // ignore
      }
    };

    const update = () => {
      scheduled = false;

      // Recompute tops on resize/font load.
      for (let i = 0; i < headingMeta.length; i++) {
        const el = document.getElementById(headingMeta[i].id);
        if (!el) continue;
        headingMeta[i].top = getHeadingTopInDocument(el);
      }

      headingMeta.sort((a, b) => a.top - b.top);

      const id = pickActiveHeadingId({
        scrollY: window.scrollY || window.pageYOffset || 0,
        headings: headingMeta
      });
      setActive(id);
    };

    const onScroll = () => {
      if (scheduled) return;
      scheduled = true;
      window.requestAnimationFrame(update);
    };

    window.addEventListener('scroll', onScroll, { passive: true });
    window.addEventListener('resize', onScroll, { passive: true });

    update();
  }

  return {
    slugifyHeading,
    pickActiveHeadingId,
    computeScrollTop,
    computeTocScrollTopToReveal,
    enhanceCollapsibleToc,
    initTocScrollSpy
  };
});
